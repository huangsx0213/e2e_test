/**
 * Migration script: split requirement-index/references/index.json
 * into per-epic resource files + generate manifest.ts
 *
 * Usage: node scripts/split-requirement-index.mjs
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const INDEX_PATH = join(ROOT, 'shared/ai/skills/requirement-index/references/index.json');
const RESOURCES_DIR = join(ROOT, 'shared/ai/skills/requirement-index/resources');

const data = JSON.parse(readFileSync(INDEX_PATH, 'utf-8'));

// Find root epics (parent === null)
const roots = data.filter(r => r.parent === null);
const byId = new Map(data.map(r => [r.id, r]));

// Build descendant sets for each root
function getDescendants(parentId) {
  const result = [];
  const queue = [parentId];
  while (queue.length > 0) {
    const current = queue.shift();
    const children = data.filter(r => r.parent === current);
    for (const child of children) {
      result.push(child.id);
      queue.push(child.id);
    }
  }
  return result;
}

// Group requirements by root epic
const epicGroups = new Map();
for (const root of roots) {
  const descendants = getDescendants(root.id);
  const epicReqs = [root, ...descendants.map(id => byId.get(id)).filter(Boolean)];
  epicGroups.set(root.id, epicReqs);
}

// Handle orphan requirements (not under any root)
const allCovered = new Set();
for (const [, reqs] of epicGroups) {
  for (const r of reqs) allCovered.add(r.id);
}
const orphans = data.filter(r => !allCovered.has(r.id));
if (orphans.length > 0) {
  epicGroups.set('_orphans', orphans);
}

// Create resources directory
if (!existsSync(RESOURCES_DIR)) {
  mkdirSync(RESOURCES_DIR, { recursive: true });
}

// Write per-epic files and build manifest entries
const manifestEntries = {};
let epicIndex = 0;

for (const [epicId, reqs] of epicGroups) {
  const fileName = epicId === '_orphans'
    ? 'requirement-orphans.json'
    : `requirement-epic-${epicId}.json`;

  const filePath = join(RESOURCES_DIR, fileName);
  writeFileSync(filePath, JSON.stringify(reqs, null, 2) + '\n');

  const sizeBytes = Buffer.byteLength(JSON.stringify(reqs), 'utf-8');
  const featureCount = reqs.filter(r => r.level === 1 || (r.parent && byId.get(r.parent)?.parent === null)).length;
  const storyCount = reqs.filter(r => r.level === 2 || (r.parent && byId.get(r.parent)?.parent && byId.get(r.parent)?.parent !== null)).length;

  // Find cross-epic references (dependencies pointing to other epics)
  const crossRefs = [];
  for (const req of reqs) {
    if (req.dependencies) {
      for (const depId of req.dependencies) {
        // Find which epic this dep belongs to
        for (const [otherEpicId] of epicGroups) {
          if (otherEpicId !== epicId) {
            const otherReqs = epicGroups.get(otherEpicId);
            if (otherReqs?.some(r => r.id === depId)) {
              const refKey = otherEpicId === '_orphans'
                ? 'resource://requirement-index/requirement-orphans.json'
                : `resource://requirement-index/requirement-epic-${otherEpicId}.json`;
              if (!crossRefs.includes(refKey)) crossRefs.push(refKey);
            }
          }
        }
      }
    }
  }

  const uri = epicId === '_orphans'
    ? 'resource://requirement-index/requirement-orphans.json'
    : `resource://requirement-index/requirement-epic-${epicId}.json`;

  const rootReq = byId.get(epicId);
  const description = epicId === '_orphans'
    ? `Orphan requirements not belonging to any epic: ${orphans.length} items`
    : `Requirements for epic "${rootReq?.title ?? epicId}": ${reqs.length} items (${featureCount} features, ${storyCount} stories)`;

  manifestEntries[`requirement-${epicId === '_orphans' ? 'orphans' : `epic-${epicId}`}`] = {
    uri,
    type: 'json',
    size: sizeBytes,
    description,
    crossRefs,
  };

  epicIndex++;
  console.log(`  [${epicIndex}] ${fileName}: ${reqs.length} requirements, ${sizeBytes} bytes`);
}

// Generate manifest.ts
const manifestContent = `// Auto-generated by scripts/split-requirement-index.mjs
// DO NOT EDIT MANUALLY — re-run the script to regenerate

export interface ResourceEntry {
  uri: string;
  type: string;
  size: number;
  description: string;
  crossRefs: string[];
}

export const resources: Record<string, ResourceEntry> = ${JSON.stringify(manifestEntries, null, 2)} as const;

export function getResourceKeys(): string[] {
  return Object.keys(resources);
}

export function getResourceByKey(key: string): ResourceEntry | undefined {
  return resources[key];
}
`;

const manifestPath = join(RESOURCES_DIR, 'manifest.ts');
writeFileSync(manifestPath, manifestContent);

console.log(`\nGenerated ${epicIndex} resource files + manifest.ts in ${RESOURCES_DIR}`);
console.log(`Total requirements: ${data.length}, Total roots: ${roots.length}`);
